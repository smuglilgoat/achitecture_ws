from math import radians, sin, cos, sqrt, atan2

# Function to calculate distance between two GPS coordinates using Haversine formula
def haversine(lat1, lon1, lat2, lon2):
    R = 6371000  # Radius of Earth in meters
    phi1, phi2 = radians(lat1), radians(lat2)
    delta_phi = radians(lat2 - lat1)
    delta_lambda = radians(lon2 - lon1)

    a = sin(delta_phi / 2)**2 + cos(phi1) * cos(phi2) * sin(delta_lambda / 2)**2
    c = 2 * atan2(sqrt(a), sqrt(1 - a))

    return R * c

# Function to match points from B to the closest points in A
def match_points(A, B):
    matched_points = []

    for lat_b, lon_b in B:
        closest_point = None
        min_distance = float('inf')
        closest_distance_from_start = None

        for lat_a, lon_a, dist_from_start in A:
            distance = haversine(lat_b, lon_b, lat_a, lon_a)
            if distance < min_distance:
                min_distance = distance
                closest_point = (lat_a, lon_a)
                closest_distance_from_start = dist_from_start

        matched_points.append((lat_b, lon_b, closest_distance_from_start))

    return matched_points

